export const LanguageContext = createContext({ lang: "ru", setLang: () => {} });

export function useLanguage() {
  return useContext(LanguageContext);
}

// t(key) reads the current language from context and falls back to Russian,
// then to the raw key, so a missing translation never crashes the UI.
export function useT() {
  const { lang } = useContext(LanguageContext);
  return (key) => translations[lang]?.[key] ?? translations.ru[key] ?? key;
}
